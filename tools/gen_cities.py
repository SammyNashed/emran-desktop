#!/usr/bin/env python3
"""Generates core/src/cities.rs from the Android app's LocationPresets.kt, so the city list is copied, not retyped."""
import pathlib, re, sys
kt = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
rows = re.findall(r'LocationPreset\("([^"]+)",\s*(-?[\d.]+),\s*(-?[\d.]+),\s*"([^"]+)"\)', kt)
ar = dict(re.findall(r'"([^"]+)" to "([^"]+)"', kt))
rows.sort(key=lambda r: r[0])
missing = [r[0] for r in rows if r[0] not in ar]
if missing: sys.exit(f"no Arabic name for {missing}")
def lit(v): return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ["// Generated by tools/gen_cities.py from the Android app's LocationPresets.kt. Do not edit by hand.", "",
       "#[derive(Debug, Clone, Copy)]", "pub struct City {", "    pub name: &'static str,", "    pub name_ar: &'static str,",
       "    pub lat: f64,", "    pub lon: f64,", "    pub zone: &'static str,", "}", "", "pub const CITIES: &[City] = &["]
for n, la, lo, z in rows:
    out.append(f"    City {{ name: {lit(n)}, name_ar: {lit(ar[n])}, lat: {float(la)!r}, lon: {float(lo)!r}, zone: {lit(z)} }},")
out += ["];", ""]
pathlib.Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8")
print(len(rows), "cities")
